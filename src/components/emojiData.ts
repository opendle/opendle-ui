/** Return the emoji whose words start with each word of the query. */
export function searchEmoji(
  query: string,
  data: readonly (readonly [string, string])[] = emojiData,
): readonly string[] {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) return data.map(([emoji]) => emoji);
  return data
    .filter(([, keywords]) => {
      const names = keywords.split(" ");
      return words.every((word) => names.some((name) => name.startsWith(word)));
    })
    .map(([emoji]) => emoji);
}
